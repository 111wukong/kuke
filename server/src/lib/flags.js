/* 运行期开关 —— 单一来源
 *
 * ── 为什么要有这个文件 ──────────────────────────────────────────
 * 这些开关有个共同点：**被多个地方读，而且读的地方必须给出同一个答案**。
 *
 * 真踩过：`KUKE_ALLOW_REGISTER` 在 auth.js 里判断一次（决定放不放行注册），
 * 又在 misc.js 里判断一次（决定前端显不显示「注册」链接）。
 * 两处各写各的 `!== '0'`，看着一样 ——
 * 直到其中一处改了默认值（比如「生产环境默认关闭」），
 * 另一处没跟着改。症状是：前端高高兴兴显示注册入口，
 * 学生填完表单点提交，收到 403「本系统已关闭自助注册」。
 * 前后端都在说实话，只是说的不是同一件事。
 *
 * 所以：**凡是「配置 + 默认值 + 派生逻辑」的组合，只能有一份实现。**
 * 这里就是那一份。
 */

export const IS_PROD = process.env.NODE_ENV === 'production';

/**
 * 自助注册开关。
 *
 * 默认值**按环境分**：
 *   生产（NODE_ENV=production）→ 默认关闭
 *   开发                        → 默认开启
 * 显式设了 KUKE_ALLOW_REGISTER 就一律听它的。
 *
 * 生产默认关的理由：这个服务要暴露在公网。默认开着等于
 * 「任何人知道域名就能注册账号」。虽然只能拿到 student 角色
 * （提权那条路已经堵死），但陌生账号会污染 users 表、
 * 干扰教师的班级管理，而且给批量注册留了一个口子。
 *
 * 老师收学生的正规路径是「建班 → 发邀请码」。
 */
export const ALLOW_REGISTER = process.env.KUKE_ALLOW_REGISTER === undefined
  ? !IS_PROD
  : process.env.KUKE_ALLOW_REGISTER !== '0';

/** 版本号。放在这里是为了让 /api/health 和 /api/misc/config 不至于各写一个。 */
export const VERSION = '1.0.0';
